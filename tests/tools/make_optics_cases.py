"""Writes tests/optics_cases.hh: point sets and scikit-learn's OPTICS on them
(ordering, reachability, core distances, predecessors, labels) and its
silhouette score, for tests/test_correlation.cc to hold mxi's OPTICS to.
Run with scikit-learn installed: python3 tests/tools/make_optics_cases.py"""

import numpy as np
import sklearn
from sklearn.cluster import OPTICS
from sklearn.metrics import silhouette_score

rng = np.random.default_rng(11)


def blobs(centres, each, spread, noise, d):
    pts = [c + rng.normal(0, spread, (each, d)) for c in centres]
    pts.append(rng.uniform(-1.5, 1.5, (noise, d)))
    return np.vstack(pts)


cases = [
    (
        "three_blobs_max_eps",
        blobs(
            [
                np.array([0.6, 0.0, 0.0]),
                np.array([0.0, 0.6, 0.0]),
                np.array([0.0, 0.0, 0.6]),
            ],
            12,
            0.04,
            6,
            3,
        ),
        5,
        0.5,
    ),
    (
        "three_blobs_no_max_eps",
        blobs(
            [
                np.array([0.6, 0.0, 0.0]),
                np.array([0.0, 0.6, 0.0]),
                np.array([0.0, 0.0, 0.6]),
            ],
            12,
            0.04,
            6,
            3,
        ),
        7,
        np.inf,
    ),
    (
        "a_grid_of_ties",
        np.array(
            [[x * 0.1, y * 0.1] for x in range(6) for y in range(5)]
            + [[2.0 + x * 0.1, 2.0] for x in range(6)]
        ),
        4,
        np.inf,
    ),
    (
        "densities_differ",
        np.vstack(
            [
                rng.normal(0, 0.02, (15, 2)),
                rng.normal([1, 1], 0.15, (15, 2)),
                rng.normal([-1, 1], 0.06, (10, 2)),
            ]
        ),
        5,
        0.8,
    ),
]


def arr(name, values, kind):
    vals = ", ".join(
        (
            ("HUGE_VAL" if np.isinf(v) else repr(float(v)))
            if kind == "double"
            else str(int(v))
        )
        for v in values
    )
    return f"  const std::vector<{kind}> {name} = {{{vals}}};\n"


out = [
    f"// Generated by tests/tools/make_optics_cases.py with scikit-learn {sklearn.__version__}.\n"
    "// Do not edit: run the script again.\n#include <cmath>\n#include <string>\n#include <vector>\n\n"
    "struct OpticsCase {\n  std::string name;\n  std::size_t n, d, min_samples;\n  double max_eps;\n"
    "  std::vector<double> points, reachability, core_distance;\n"
    "  std::vector<long> ordering, predecessor;\n  std::vector<int> labels;\n  double silhouette;\n};\n\n"
    "inline std::vector<OpticsCase> optics_cases() {\n  std::vector<OpticsCase> cases;\n"
]
for name, pts, ms, eps in cases:
    m = OPTICS(min_samples=ms, xi=0.05, max_eps=eps).fit(pts)
    mask = m.labels_ != -1
    sil = (
        silhouette_score(pts[mask], m.labels_[mask])
        if len(set(m.labels_[mask])) > 1
        else 0.0
    )
    out.append("  {\n")
    out.append(arr("points", pts.ravel(), "double"))
    out.append(arr("reachability", m.reachability_, "double"))
    out.append(arr("core", m.core_distances_, "double"))
    out.append(arr("ordering", m.ordering_, "long"))
    out.append(arr("predecessor", m.predecessor_, "long"))
    out.append(arr("labels", m.labels_, "int"))
    e = "HUGE_VAL" if np.isinf(eps) else repr(float(eps))
    out.append(
        f'    cases.push_back({{"{name}", {pts.shape[0]}, {pts.shape[1]}, {ms}, {e}, points, '
        f"reachability, core, ordering, predecessor, labels, {sil!r}}});\n  }}\n"
    )
    print(
        f"{name}: {pts.shape[0]} points, labels {sorted(set(m.labels_.tolist()))}, silhouette {sil:.4f}"
    )
out.append("  return cases;\n}\n")
open("tests/optics_cases.hh", "w").write("".join(out))
