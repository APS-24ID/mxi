#!/usr/bin/env python3
"""Write docs/commands.md: every mxi command's options, from its own --help.

The reference is generated, not written, so that it cannot fall behind:
python/tests/test_command_reference.py regenerates it and fails when the file
differs. After changing a command's options:

    python3 scripts/command_reference.py build/mxi > docs/commands.md
"""

import re
import subprocess
import sys

HEADER = """\
# Every command's options

STATUS: generated by `scripts/command_reference.py` from each command's own
`--help`; `python/tests/test_command_reference.py` fails when it is out of
date. The documents named in [`docs/README.md`](README.md) say what the
programs do and why; this says what each takes. Every command also takes
`-j N`, `--threads N`: the threads for everything it does in parallel.

"""


def commands(mxi):
    """The commands mxi's own --help lists, with their one-line summaries,
    leaving out those that only say where they moved."""
    text = subprocess.run([mxi, "--help"], capture_output=True, text=True).stdout
    out = []
    for line in text.splitlines():
        m = re.match(r"^  ([a-z]+)\s{2,}(.+)$", line)
        if m and not m.group(2).startswith("now "):
            out.append((m.group(1), m.group(2).strip()))
    return out


def reference(mxi):
    parts = [HEADER]
    listed = commands(mxi)
    parts.append(
        "| command | |\n|---|---|\n"
        + "".join(f"| [`mxi {c}`](#mxi-{c}) | {what} |\n" for c, what in listed)
        + "\n"
    )
    for c, what in listed:
        r = subprocess.run([mxi, c, "--help"], capture_output=True, text=True)
        help_text = (r.stdout + r.stderr).rstrip("\n")
        parts.append(f"## mxi {c}\n\n{what}.\n\n```\n{help_text}\n```\n\n")
    return "".join(parts).rstrip("\n") + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: command_reference.py MXI")
    sys.stdout.write(reference(sys.argv[1]))
