"""docs/commands.md is every command's own --help, as it stands.

The reference is generated by scripts/command_reference.py, so an option
added, renamed or removed without regenerating it fails here. And each help
text is checked for what a mechanical edit left behind once: a word or two at
the margin between option lines -- "(0)", "from", "one", "the" -- and a usage
line with an option's text spliced into it (13 November, in five commands).
"""

import os
import pathlib
import subprocess
import sys

import pytest

BUILD = os.path.dirname(os.environ.get("MXI_FIND", "")) or os.environ.get(
    "MXI_BUILD", ""
)
MXI = os.path.join(BUILD, "mxi")
ROOT = pathlib.Path(__file__).resolve().parents[2]

pytestmark = pytest.mark.skipif(not os.path.exists(MXI), reason="mxi is not built")

sys.path.insert(0, str(ROOT / "scripts"))
import command_reference  # noqa: E402


def test_the_reference_is_every_commands_help_as_it_stands():
    written = (ROOT / "docs" / "commands.md").read_text()
    now = command_reference.reference(MXI)
    assert written == now, (
        "docs/commands.md is out of date: "
        "python3 scripts/command_reference.py build/mxi > docs/commands.md"
    )


def test_no_help_has_a_stray_fragment_or_a_spliced_usage_line():
    found = []
    for name, _ in command_reference.commands(MXI):
        lines = subprocess.run(
            [MXI, name, "--help"], capture_output=True, text=True
        ).stdout.split("\n")
        if "  -j, --threads" in lines[0]:
            found.append(f"mxi {name}: its usage line runs into -j")
        for k, line in enumerate(lines):
            if not line or line.startswith((" ", "usage")):
                continue
            before = lines[k - 1] if k else ""
            after = lines[k + 1] if k + 1 < len(lines) else ""
            if len(line.split()) <= 3 and (
                before.startswith("  ") or after.startswith("   ")
            ):
                found.append(f"mxi {name}, line {k + 1}: {line!r}")
    assert not found, found
